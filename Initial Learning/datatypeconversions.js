// Just covering the basic datatype conversions first to build the understanding

let studentScore = 100;
console.log(studentScore);

// String -> Its the most easy and understandable conversion

let stringstudentScore = String(studentScore);
console.log(stringstudentScore);

//Boolean -> okayish
let BooleanstudentScore = Boolean(stringstudentScore);
console.log(BooleanstudentScore);

//Number
let againnumberstudentScore = Number(BooleanstudentScore);
console.log(againnumberstudentScore);